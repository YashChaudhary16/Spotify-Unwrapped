#!/usr/bin/env node
/**
 * Regenerates lib/countryTimezones.ts from the IANA tz database's zone.tab.
 *
 *   node scripts/generate-country-timezones.mjs [path/to/zone.tab]
 *
 * Defaults to /usr/share/zoneinfo/zone.tab (present on Linux/macOS).
 * Spotify only tells us the connection *country*, so each country gets ONE timezone:
 *   - single-zone countries: that zone
 *   - multi-zone countries: the zone where most people live (usually the capital's), from PRIMARY below
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const zoneTabPath = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab';
const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'countryTimezones.ts');

/** Primary zone for every country that spans several timezones. */
const PRIMARY = {
  AQ: 'Antarctica/McMurdo',
  AR: 'America/Argentina/Buenos_Aires',
  AU: 'Australia/Sydney',
  BR: 'America/Sao_Paulo',
  CA: 'America/Toronto',
  CD: 'Africa/Kinshasa',
  CL: 'America/Santiago',
  CN: 'Asia/Shanghai',
  CY: 'Asia/Nicosia',
  DE: 'Europe/Berlin',
  EC: 'America/Guayaquil',
  ES: 'Europe/Madrid',
  FM: 'Pacific/Pohnpei',
  GL: 'America/Nuuk',
  ID: 'Asia/Jakarta',
  KI: 'Pacific/Tarawa',
  KZ: 'Asia/Almaty',
  MH: 'Pacific/Majuro',
  MN: 'Asia/Ulaanbaatar',
  MX: 'America/Mexico_City',
  MY: 'Asia/Kuala_Lumpur',
  NZ: 'Pacific/Auckland',
  PF: 'Pacific/Tahiti',
  PG: 'Pacific/Port_Moresby',
  PS: 'Asia/Hebron',
  PT: 'Europe/Lisbon',
  RU: 'Europe/Moscow',
  UA: 'Europe/Kyiv',
  UM: 'Pacific/Wake',
  US: 'America/New_York',
  UZ: 'Asia/Tashkent',
};

/** Codes Spotify can report that zone.tab doesn't list. */
const EXTRA = {
  XK: 'Europe/Belgrade', // Kosovo
};

const zonesByCountry = new Map();
for (const line of readFileSync(zoneTabPath, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [code, , zone] = line.split('\t');
  if (!zonesByCountry.has(code)) zonesByCountry.set(code, []);
  zonesByCountry.get(code).push(zone);
}

const entries = [];
const problems = [];
for (const [code, zones] of [...zonesByCountry.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  if (zones.length === 1) {
    entries.push([code, zones[0]]);
  } else if (PRIMARY[code] && zones.includes(PRIMARY[code])) {
    entries.push([code, PRIMARY[code]]);
  } else {
    problems.push(`${code}: no valid PRIMARY entry (zones: ${zones.join(', ')})`);
  }
}
for (const [code, zone] of Object.entries(EXTRA)) {
  if (!zonesByCountry.has(code)) entries.push([code, zone]);
}
entries.sort(([a], [b]) => a.localeCompare(b));
if (problems.length) {
  console.error('Fix PRIMARY for:\n' + problems.join('\n'));
  process.exit(1);
}

const version = (() => {
  try {
    return readFileSync(join(dirname(zoneTabPath), 'tzdata.zi'), 'utf8').match(/^# version (\S+)/m)?.[1] ?? 'unknown';
  } catch {
    return 'unknown';
  }
})();

const body = entries.map(([code, zone]) => `  ${code}: '${zone}',`).join('\n');
writeFileSync(
  outPath,
  `// GENERATED by scripts/generate-country-timezones.mjs from IANA tz ${version} zone.tab — do not edit by hand.
// One IANA timezone per ISO 3166-1 alpha-2 country code. Multi-zone countries use their most populous zone.

export const COUNTRY_TIMEZONES: Record<string, string> = {
${body}
};
`
);
console.log(`Wrote ${entries.length} countries to ${outPath} (tz ${version})`);
